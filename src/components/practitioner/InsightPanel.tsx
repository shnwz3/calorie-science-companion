import { Eye, HelpCircle, Lightbulb, ShieldAlert } from "lucide-react";
import type { ReactNode } from "react";
import { Card, SectionTitle } from "@/components/ui";
import type { Insight, Statement } from "@/lib/insights";

function Group({ icon, title, tag, tone, items }: { icon: ReactNode; title: string; tag: string; tone: string; items: Statement[] }) {
  if (!items.length) return null;
  return (
    <div>
      <div className="mb-2.5 flex flex-wrap items-center gap-1.5">
        {icon}
        <h3 className="text-sm font-semibold text-stone-800">{title}</h3>
        <span className={`ml-auto rounded-md px-1.5 py-0.5 text-xs font-medium ${tone}`}>{tag}</span>
      </div>
      <ul className="space-y-2.5">
        {items.map((s, i) => (
          <li key={i} className="relative pl-3.5 text-sm leading-relaxed text-stone-800">
            <span aria-hidden="true" className="absolute left-0 top-[0.6rem] h-1 w-1 rounded-full bg-stone-400" />
            {s.text}
            {s.evidence && <p className="mt-0.5 text-[0.8125rem] leading-snug text-stone-500">{s.evidence}</p>}
          </li>
        ))}
      </ul>
    </div>
  );
}

export function InsightPanel({ insight }: { insight: Insight }) {
  return (
    <Card className="p-5">
      <SectionTitle title="What appears to be happening" subtitle={insight.basis} />
      <div className="space-y-6">
        <Group
          icon={<Eye className="h-4 w-4 text-stone-500" />}
          title="Observed"
          tag="from logs"
          tone="bg-stone-100 text-stone-600"
          items={insight.observed}
        />
        <Group
          icon={<HelpCircle className="h-4 w-4 text-plum-500" />}
          title="Possible explanations"
          tag="assumption · not confirmed"
          tone="bg-plum-50 text-plum-700"
          items={insight.possible}
        />
        <Group
          icon={<Lightbulb className="h-4 w-4 text-amber-500" />}
          title="You may want to consider"
          tag="suggestion"
          tone="bg-amber-50 text-amber-700"
          items={insight.consider}
        />
      </div>
      <p className="mt-4 flex items-start gap-1.5 border-t border-stone-100 pt-3 text-xs text-stone-500">
        <ShieldAlert className="mt-0.5 h-3.5 w-3.5 shrink-0" />
        Generated by transparent rules from logged data. Not a clinical assessment. Clinical judgement stays with the practitioner.
      </p>
    </Card>
  );
}
